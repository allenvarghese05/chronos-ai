"""Pydantic -> JSON schema -> zod, in-repo and dependency-free (T3.4 owner decision 1).

Supports exactly the JSON-schema subset our renderer models use: objects (required vs
optional), strings (minLength/maxLength/pattern/format uri), numbers (minimum,
exclusiveMinimum), integers, enums/consts, arrays (items, minItems/maxItems), local ``$ref``s
and ``anyOf [T, null]`` (emitted as ``T.optional()`` - serialised props omit ``None``).
Anything else raises, so an unsupported model change fails loudly instead of drifting.

Output is formatted the way the renderer's Biome config expects (tabs, single quotes,
trailing commas) so ``biome ci`` passes on the generated file, and is byte-deterministic so
CI can diff it.
"""

from __future__ import annotations

import json
from typing import Any, cast

from chronos.media.reel_props import ReelProps

HEADER = (
    "// GENERATED by `chronos schema export-reel-props` from\n"
    "// services/api/src/chronos/media/reel_props.py. Do not edit; run `just gen-types`.\n"
)


def _q(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _type(node: dict[str, Any], indent: int) -> str:
    if "$ref" in node:
        return f"{str(node['$ref']).removeprefix('#/$defs/')}Schema"
    if "anyOf" in node:
        options = [cast("dict[str, Any]", o) for o in node["anyOf"]]
        non_null = [o for o in options if o.get("type") != "null"]
        if len(non_null) != 1 or len(options) != 2:
            raise ValueError(f"unsupported anyOf: {node}")
        return _type(non_null[0], indent)
    if "const" in node:
        return f"z.literal({_q(str(node['const']))})"
    if "enum" in node:
        values = ", ".join(_q(str(v)) for v in node["enum"])
        return f"z.enum([{values}])"
    kind = node.get("type")
    if kind == "string":
        out = "z.string()"
        if node.get("format") == "uri":
            out += ".url()"
        if "minLength" in node:
            out += f".min({node['minLength']})"
        if "maxLength" in node:
            out += f".max({node['maxLength']})"
        if "pattern" in node:
            pattern = str(node["pattern"]).replace("/", "\\/")
            out += f".regex(/{pattern}/)"
        return out
    if kind in ("number", "integer"):
        out = "z.number()" + (".int()" if kind == "integer" else "")
        if "exclusiveMinimum" in node:
            out += (
                ".positive()"
                if node["exclusiveMinimum"] == 0
                else (f".gt({node['exclusiveMinimum']})")
            )
        if "minimum" in node:
            out += ".nonnegative()" if node["minimum"] == 0 else f".min({node['minimum']})"
        return out
    if kind == "array":
        out = f"z.array({_type(cast('dict[str, Any]', node['items']), indent)})"
        if "minItems" in node:
            out += f".min({node['minItems']})"
        if "maxItems" in node:
            out += f".max({node['maxItems']})"
        return out
    if kind == "object":
        return _object(node, indent)
    raise ValueError(f"unsupported schema node: {node}")


def _object(node: dict[str, Any], indent: int) -> str:
    props = cast("dict[str, dict[str, Any]]", node.get("properties", {}))
    required = set(cast("list[str]", node.get("required", [])))
    pad = "\t" * (indent + 1)
    lines = ["z.object({"]
    for name, prop in props.items():
        expr = _type(prop, indent + 1)
        if name not in required:
            expr += ".optional()"
        lines.append(f"{pad}{name}: {expr},")
    lines.append("\t" * indent + "})")
    return "\n".join(lines)


def _refs(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        mapping = cast("dict[str, Any]", node)
        ref = mapping.get("$ref")
        if isinstance(ref, str):
            found.add(ref.removeprefix("#/$defs/"))
        for value in mapping.values():
            found |= _refs(value)
    elif isinstance(node, list):
        for value in cast("list[Any]", node):
            found |= _refs(value)
    return found


def reel_props_json_schema() -> dict[str, Any]:
    return ReelProps.model_json_schema()


def zod_source(schema: dict[str, Any] | None = None) -> str:
    """TypeScript module exporting one zod schema per model, dependencies first."""
    schema = schema or reel_props_json_schema()
    defs = cast("dict[str, dict[str, Any]]", schema.get("$defs", {}))
    ordered: list[str] = []

    def visit(name: str, stack: tuple[str, ...]) -> None:
        if name in ordered:
            return
        if name in stack:
            raise ValueError(f"recursive model: {' -> '.join((*stack, name))}")
        for dep in sorted(_refs(defs[name])):
            visit(dep, (*stack, name))
        ordered.append(name)

    for name in sorted(defs):
        visit(name, ())
    top = {k: v for k, v in schema.items() if k != "$defs"}
    blocks = [HEADER, "import { z } from 'zod';\n"]
    for name in ordered:
        blocks.append(f"export const {name}Schema = {_type(defs[name], 0)};\n")
    blocks.append(f"export const {schema['title']}BaseSchema = {_type(top, 0)};\n")
    return "\n".join(blocks)


def schema_json_text(schema: dict[str, Any] | None = None) -> str:
    return json.dumps(schema or reel_props_json_schema(), sort_keys=True, indent="\t") + "\n"
