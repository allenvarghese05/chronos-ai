#!/usr/bin/env bash
# scripts/laptop-setup.sh — idempotent one-time setup for this Mac (T0.6)
#
# What it does (non-sudo):
#   1. Creates data/{logs,models/kokoro,models/whisper,certs} directories
#   2. Creates services/api/.env if missing (auto-generates CHRONOS_SECRET_KEY)
#   3. Calls scripts/certs.sh to generate TLS certs
#   4. Renders LaunchAgent plist templates → ~/Library/LaunchAgents/
#   5. Loads/reloads both LaunchAgents
#   6. Starts Ollama via brew services
#
# What requires sudo (printed as "RUN THIS" if non-interactive):
#   A. mkcert -install (handled inside scripts/certs.sh)
#   B. pmset repeat (wake schedule)
#
# Usage: scripts/laptop-setup.sh [--skip-certs] [--skip-plists]
#
# After running this script, manually complete the owner checklist printed at the end.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
LAUNCHAGENTS_DIR="${HOME}/Library/LaunchAgents"

SKIP_CERTS=0
SKIP_PLISTS=0

for arg in "$@"; do
    case "$arg" in
        --skip-certs)  SKIP_CERTS=1  ;;
        --skip-plists) SKIP_PLISTS=1 ;;
        *) echo "Unknown argument: $arg" >&2; exit 1 ;;
    esac
done

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "  → $*"; }
ok()   { echo "  ✓ $*"; }
warn() { echo "  ⚠ $*"; }

is_interactive() { [ -t 0 ] && [ -t 1 ]; }

echo ""
echo "╔══════════════════════════════════════════════════════════╗"
echo "║  Chronos-AI laptop setup (T0.6)                          ║"
echo "║  Repo: ${REPO_ROOT}"
echo "╚══════════════════════════════════════════════════════════╝"
echo ""

# ─────────────────────────────────────────────────────────────────────────────
# 1. Create data directories
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 1: Creating data directories..."
mkdir -p \
    "${REPO_ROOT}/data/logs" \
    "${REPO_ROOT}/data/models/kokoro" \
    "${REPO_ROOT}/data/models/whisper" \
    "${REPO_ROOT}/data/certs"
ok "data/ subdirectories created."

# ─────────────────────────────────────────────────────────────────────────────
# 2. Create .env if missing
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 2: Checking services/api/.env..."
ENV_FILE="${REPO_ROOT}/services/api/.env"

if [ ! -f "${ENV_FILE}" ]; then
    info "Creating ${ENV_FILE} from template..."

    # Detect LAN IP
    LAN_IP="${CHRONOS_LAN_IP:-$(ipconfig getifaddr en0 2>/dev/null || echo "127.0.0.1")}"
    HOSTNAME_LOCAL="$(scutil --get LocalHostName 2>/dev/null || echo "allen-macbook").local"

    # Generate secret key (48 bytes → 64 chars base64url)
    SECRET_KEY=$(python3 -c "import secrets; print(secrets.token_urlsafe(48))")

    cat > "${ENV_FILE}" <<EOF
# Generated by scripts/laptop-setup.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Review and adjust before deploying.

# ── environment ──────────────────────────────────────────────────────────────
CHRONOS_ENV=prod

# ── security (REQUIRED) ───────────────────────────────────────────────────────
CHRONOS_SECRET_KEY=${SECRET_KEY}

# ── server ────────────────────────────────────────────────────────────────────
CHRONOS_API_BIND_HOST=${LAN_IP}
CHRONOS_API_BIND_PORT=8443

# ── public URL ────────────────────────────────────────────────────────────────
CHRONOS_PUBLIC_BASE_URL=https://${HOSTNAME_LOCAL}:8443/v1

# ── TLS (required in prod) ────────────────────────────────────────────────────
CHRONOS_TLS_CERT=${REPO_ROOT}/data/certs/chronos-lan.pem
CHRONOS_TLS_KEY=${REPO_ROOT}/data/certs/chronos-lan-key.pem

# ── database ──────────────────────────────────────────────────────────────────
CHRONOS_DATABASE_URL=sqlite:///${REPO_ROOT}/data/chronos.db

# ── logging ───────────────────────────────────────────────────────────────────
CHRONOS_LOG_DIR=${REPO_ROOT}/data/logs

# ── LLM / Ollama ──────────────────────────────────────────────────────────────
CHRONOS_OLLAMA_ENDPOINT=http://localhost:11434
CHRONOS_LLM_PROVIDER=ollama
EOF

    chmod 600 "${ENV_FILE}"
    ok ".env created with random secret key (mode 600)."
    info "Detected LAN IP: ${LAN_IP} — verify this is correct."
else
    # Ensure .env is mode 600
    chmod 600 "${ENV_FILE}"
    ok ".env already exists (mode set to 600)."
fi

# ─────────────────────────────────────────────────────────────────────────────
# 3. Generate TLS certs
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 3: Generating TLS certificates..."
if [ "${SKIP_CERTS}" = "1" ]; then
    warn "Skipping cert generation (--skip-certs)."
else
    bash "${SCRIPT_DIR}/certs.sh"
fi

# ─────────────────────────────────────────────────────────────────────────────
# 4. Render and install LaunchAgent plists
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 4: Installing LaunchAgent plists..."

if [ "${SKIP_PLISTS}" = "1" ]; then
    warn "Skipping plist installation (--skip-plists)."
else
    mkdir -p "${LAUNCHAGENTS_DIR}"

    # Detect uv binary path
    UV_BIN="$(command -v uv || echo "/opt/homebrew/bin/uv")"

    for AGENT in api deploy; do
        TEMPLATE="${SCRIPT_DIR}/launchd/com.chronos.${AGENT}.plist.template"
        DEST="${LAUNCHAGENTS_DIR}/com.chronos.${AGENT}.plist"

        [ -f "${TEMPLATE}" ] || die "Template not found: ${TEMPLATE}"

        # Render template: replace __REPO_ROOT__, __HOME__, __UV__
        sed \
            -e "s|__REPO_ROOT__|${REPO_ROOT}|g" \
            -e "s|__HOME__|${HOME}|g" \
            -e "s|__UV__|${UV_BIN}|g" \
            "${TEMPLATE}" > "${DEST}"

        # Validate the rendered plist (macOS built-in)
        if ! plutil -lint "${DEST}" >/dev/null 2>&1; then
            die "plutil -lint failed for ${DEST}. This is a bug in the template."
        fi

        info "Rendered and validated: ${DEST}"

        # Unload if already loaded (idempotent); ignore errors
        launchctl bootout "gui/${UID}" "${DEST}" 2>/dev/null || true

        # Load the agent
        launchctl bootstrap "gui/${UID}" "${DEST}"
        ok "Loaded: com.chronos.${AGENT}"
    done
fi

# ─────────────────────────────────────────────────────────────────────────────
# 5. Start Ollama via brew services
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 5: Starting Ollama..."
if command -v brew >/dev/null 2>&1; then
    brew services start ollama 2>/dev/null || true
    ok "Ollama service started (or already running)."
else
    warn "brew not found; start Ollama manually: ollama serve"
fi

# ─────────────────────────────────────────────────────────────────────────────
# 6. pmset wake schedule (requires sudo — interactive or printed)
# ─────────────────────────────────────────────────────────────────────────────
echo "Step 6: pmset wake schedule..."

PMSET_WEEKDAY="sudo pmset repeat wakeorpoweron MTWRF 05:25:00 SU 07:25:00"

# Check if schedule already set
if pmset -g sched 2>/dev/null | grep -q "05:25"; then
    ok "Wake schedule already set (05:25 weekday, 07:25 weekend)."
else
    if is_interactive; then
        echo "  Setting wake schedule (requires sudo)..."
        eval "${PMSET_WEEKDAY}"
        ok "Wake schedule set."
    else
        echo ""
        echo "  ╔══════════════════════════════════════════════════════════════╗"
        echo "  ║  RUN THIS (requires sudo) — set laptop wake schedule:        ║"
        echo "  ║                                                              ║"
        printf "  ║  %-62s║\n" "${PMSET_WEEKDAY}"
        echo "  ╚══════════════════════════════════════════════════════════════╝"
        echo ""
    fi
fi

# ─────────────────────────────────────────────────────────────────────────────
# 7. Summary and owner checklist
# ─────────────────────────────────────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  Setup complete. Verify with:                                ║"
echo "║    launchctl list | grep com.chronos                         ║"
echo "║    just doctor                                               ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
echo "=== Owner checklist (items requiring manual action) ==="
echo ""
echo "  [sudo] 1. Install mkcert root CA in system keychain:"
echo "             mkcert -install"
echo ""
echo "  [sudo] 2. Set laptop wake schedule (if not done above):"
echo "             sudo pmset repeat wakeorpoweron MTWRF 05:25:00 SU 07:25:00"
echo ""
echo "  [sudo] 3. Allow API through macOS firewall:"
echo "             sudo /usr/libexec/ApplicationFirewall/socketfilterfw \\"
echo "               --add \$(which uv) --unblockapp \$(which uv)"
echo ""
echo "  [iPhone] 4. Install root CA on iPhone:"
echo "              a. python3 -m http.server 8080 --directory '${REPO_ROOT}/data/certs'"
echo "              b. On iPhone Safari: http://$(ipconfig getifaddr en0 2>/dev/null || echo '<LAN_IP>'):8080/rootCA.pem"
echo "              c. Settings → Profile Downloaded → Install → Trust"
echo ""
echo "  [verify] 5. curl --cacert data/certs/rootCA.pem https://allen-macbook.local:8443/healthz"
echo "  [verify] 6. just models    (download Kokoro + whisper + Ollama model)"
echo "  [verify] 7. just doctor    (should show all checks green/warn)"
echo ""
